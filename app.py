# =========================
# DETECTION (FIXED PRIORITY)
# =========================

def detect_emotion(text):
    t = text.lower()

    if any(w in t for w in ["умор", "измор", "tired"]):
        return "fatigue"

    if any(w in t for w in ["стрес", "stress"]):
        return "stress"

    if any(w in t for w in ["тъж", "sad"]):
        return "sad"

    if any(w in t for w in ["страх", "тревож"]):
        return "anxiety"

    if any(w in t for w in ["яд", "гнев"]):
        return "anger"

    return "neutral"

def get_response(text):
    return random.choice(EMOTION_BANK[detect_emotion(text)])

