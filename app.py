RECOVERY_WORDS = ["уморен","изморен","изтощен","капнал","нямам сила","прегорял","изцеден","сринат","изчерпан"]
STRESS_WORDS = ["стрес","напрежение","претоварен","хаос","паника","притиснат","натиск"]
SAD_WORDS = ["тъжен","сам","празно","болка","потиснат","разбит","отчаян"]
ANGER_WORDS = ["ядосан","гневен","бесен","яд ме е","вбесен","раздразнен"]
WORK_WORDS = ["работа","задачи","deadline","претоварен с работа","график"]
INSPO_WORDS = ["щастлив","радост","вдъхновен","усмихнат","добре ми е","хубаво ми е","радвам се"]
NEUTRAL_WORDS = ["ок","нормално","спокойно","добре съм","без промяна"]

def match(words, text):
    return any(w in text for w in words)

def detect(text):
    ttxt = text.lower()

    if match(RECOVERY_WORDS, ttxt):
        return "recovery"
    if match(STRESS_WORDS, ttxt):
        return "stress"
    if match(SAD_WORDS, ttxt):
        return "sad"
    if match(ANGER_WORDS, ttxt):
        return "anger"
    if match(WORK_WORDS, ttxt):
        return "work"
    if match(INSPO_WORDS, ttxt):
        return "inspiration"
    return "neutral"

